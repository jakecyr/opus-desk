test('conflict repair keeps both parents, includes only resolved files, and records tests', async (t) => {
  const { prepareAutomaticCheckout, collectAutomaticFix } =
    await import('../server/auto-checkout.js');
  const { run } = await import('../server/core.js');
  const sandbox = await fs.mkdtemp(
    path.join(os.tmpdir(), 'opusdesk-auto-conflict-'),
  );
  t.after(() => fs.rm(sandbox, { recursive: true, force: true }));
  const repo = path.join(sandbox, 'repo');
  const directory = path.join(sandbox, 'task');
  const git = (...args) => run('git', ['-C', repo, ...args]);
  await run('git', ['init', '-q', '-b', 'main', repo]);
  await git('config', 'user.name', 'Opus Test');
  await git('config', 'user.email', 'test@example.org');
  await git('config', 'commit.gpgsign', 'false');
  await fs.writeFile(path.join(repo, 'example.txt'), 'original\n');
  await git('add', 'example.txt');
  await git('commit', '-qm', 'initial');
  await git('checkout', '-qb', 'pr');
  await fs.writeFile(path.join(repo, 'example.txt'), 'proposed\n');
  await git('commit', '-qam', 'proposed');
  const head = (await git('rev-parse', 'HEAD')).trim();
  await git('update-ref', 'refs/pull/1/head', head);
  await git('checkout', '-q', 'main');
  await fs.writeFile(path.join(repo, 'example.txt'), 'changed on base\n');
  await git('commit', '-qam', 'base changed');
  const base = (await git('rev-parse', 'HEAD')).trim();
  const execute = (command, args, opts) =>
    run(
      command,
      args.map((arg) => (arg === 'https://github.com/a/b.git' ? repo : arg)),
      opts,
    );
  const { cwd } = await prepareAutomaticCheckout(
    {
      directory,
      project: repo,
      pull: pr({ headRefOid: head, baseRefOid: base, baseRefName: 'main' }),
      kind: 'conflicts',
    },
    execute,
  );
  const resolved = path.join(cwd, 'example.txt');
  assert.match(await fs.readFile(resolved, 'utf8'), /<<<<<<< HEAD/);
  await fs.writeFile(resolved, 'resolved contents\n');
  const artifact = path.join(cwd, 'opus-result.json');
  await fs.writeFile(
    artifact,
    JSON.stringify({ tested: true, checks: ['node --test'] }),
  );
  const result = await collectAutomaticFix(
    { cwd, artifact, kind: 'conflicts', base, initialHead: head },
    execute,
  );
  assert.deepEqual(result, { tested: true, checks: ['node --test'] });
  const parents = (
    await run('git', ['-C', cwd, 'log', '-1', '--format=%P'])
  ).trim();
  assert.equal(parents, head + ' ' + base);
  assert.equal(
    (await run('git', ['-C', cwd, 'status', '--porcelain'])).trim(),
    '',
  );
  assert.equal(
    await fs.readFile(path.join(repo, 'example.txt'), 'utf8'),
    'changed on base\n',
  );
});

test('a written review submits only its explicit text and refuses to replace a draft', async () => {
  const { submitReviewText } = await import('../server/publications.js');
  let pending = false;
  const writes = [];
  const execute = async (_file, args) => {
    if (args[0] === 'pr') return '{"headRefOid":"head","state":"OPEN"}';
    if (args.at(-1) === 'user') return '{"login":"me"}';
    if (!args.includes('--method'))
      return JSON.stringify([
        pending ? [{ id: 99, state: 'PENDING', user: { login: 'me' } }] : [],
      ]);
    writes.push(JSON.parse(await fs.readFile(args.at(-1), 'utf8')));
    return '{"id":2}';
  };
  await assert.rejects(
    submitReviewText(url, 'head', '  ', execute),
    /review feedback/,
  );
  await assert.rejects(
    submitReviewText(url, 'old-sha', 'Looks right', execute),
    /PR changed/,
  );
  pending = true;
  await assert.rejects(
    submitReviewText(url, 'head', 'Looks right', execute),
    /pending GitHub review/,
  );
  pending = false;
  await submitReviewText(url, 'head', '  Verified the test case.  ', execute);
  assert.deepEqual(writes, [
    {
      commit_id: 'head',
      body: 'Verified the test case.',
      comments: [],
      event: 'COMMENT',
    },
  ]);
});

test('automatic code publishing rechecks ownership, CI and authorization before pushing', async () => {
  const { publishPrepared } = await import('../server/publications.js');
  let ci = 'FAILURE';
  let viewer = 'me';
  let author = 'me';
  let head = 'head';
  const writes = [];
  const execute = async (file, args) => {
    if (file === 'gh')
      return JSON.stringify({
        data: {
          viewer: { login: viewer },
          p0: {
            pullRequest: {
              state: 'OPEN',
              headRefOid: head,
              author: { login: author },
              commits: {
                nodes: [{ commit: { statusCheckRollup: { state: ci } } }],
              },
            },
          },
        },
      });
    if (args.includes('rev-parse')) return 'repair';
    if (args.includes('push')) writes.push(args);
    return '';
  };
  const task = {
    auto: true,
    viewer: 'me',
    cwd: '/checkout',
    kind: 'ci',
    type: 'code',
    status: 'pending',
    url,
    head: 'repair',
    pr: {
      headRefOid: 'head',
      headRefName: 'feature',
      headRepository: { name: 'fork' },
      headRepositoryOwner: { login: 'me' },
    },
  };
  ci = 'SUCCESS';
  await assert.rejects(publishPrepared(task, execute), /Re-run/);
  ci = 'FAILURE';
  viewer = 'new-account';
  await assert.rejects(publishPrepared(task, execute), /Re-run/);
  viewer = 'me';
  author = 'someone-else';
  await assert.rejects(publishPrepared(task, execute), /Re-run/);
  author = 'me';
  head = 'advanced';
  await assert.rejects(publishPrepared(task, execute), /Re-run/);
  head = 'head';
  await assert.rejects(
    publishPrepared(task, execute, () => false),
    /settings changed/,
  );
  assert.equal(writes.length, 0);
  await publishPrepared(task, execute);
  assert.equal(writes.length, 1);
  assert.deepEqual(writes[0].slice(-3), [
    'push',
    'https://github.com/me/fork.git',
    'repair:refs/heads/feature',
  ]);
});

test('Enterprise merge respects branch-preferred methods and requires the current head', async () => {
  const { setGithubHost } = await import('../server/core.js');
  const { mergePull } = await import('../server/pulls.js');
  const enterprise = 'https://git.corp.test/team/repo/pull/2';
  const writes = [];
  const execute = async (_file, args) => {
    if (args.includes('graphql'))
      return JSON.stringify({
        data: {
          viewer: { login: 'me' },
          p0: {
            pullRequest: {
              state: 'OPEN',
              headRefOid: 'head',
              mergeable: 'MERGEABLE',
              mergeStateStatus: 'CLEAN',
            },
          },
        },
      });
    if (args.includes('view'))
      return JSON.stringify({ baseRefName: 'release/v1' });
    if (args.at(-1) === 'repos/team/repo')
      return '{"allow_squash_merge":true,"allow_merge_commit":true}';
    if (args.at(-1) === 'repos/team/repo/rules/branches/release%2Fv1')
      return '[{"type":"pull_request","parameters":{"allowed_merge_methods":["merge"]}}]';
    writes.push(args);
    return '';
  };
  setGithubHost('git.corp.test');
  try {
    await assert.rejects(mergePull(enterprise, 'stale', execute), /changed/);
    assert.equal(writes.length, 0);
    await mergePull(enterprise, 'head', execute);
    assert.deepEqual(writes, [
      ['pr', 'merge', enterprise, '--merge', '--match-head-commit', 'head'],
    ]);
  } finally {
    setGithubHost('github.com');
  }
});
