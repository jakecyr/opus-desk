const url = 'https://github.com/a/b/pull/1';
const pr = (overrides) => ({
  url,
  headRefOid: 'head',
  baseRefOid: 'base',
  statusReady: true,
  state: 'OPEN',
  roles: ['review'],
  ...overrides,
});
const candidates = (item, history = {}, settings = {}, tasks = {}) =>
  autoCandidates(
    { prs: [item], issues: [{ url: 'https://github.com/a/b/issues/1' }] },
    history,
    settings,
    tasks,
  );

test('automatic reviews require a request or a new response and skip drafts and authored PRs', () => {
  assert.equal(candidates(pr())[0].action, 'review');
  for (const override of [
    { roles: ['assigned'] },
    { roles: ['reviewed'], reviewedByMe: true },
    { reviewedByMe: true, reviewedCurrentHead: true },
    { pendingReview: true },
    { isDraft: true },
    { statusReady: false },
    { state: 'CLOSED' },
    { roles: ['authored', 'review'] },
  ])
    assert.deepEqual(candidates(pr(override)), []);
  const response = pr({
    roles: ['reviewed'],
    reviewedByMe: true,
    reviewedCurrentHead: true,
    responseFingerprint: 'thread:time',
  });
  const [job] = candidates(response);
  assert.equal(job.action, 'rereview');
  assert.equal(job.kind, 'review');
  const history = { [job.key]: { status: 'failed' } };
  assert.deepEqual(candidates(response, history), []);
  assert.equal(
    candidates({ ...response, responseFingerprint: 'thread:time2' }, history)
      .length,
    1,
  );
});

test('auto repairs prioritize conflicts and never chase checks generated by the previous automatic push', () => {
  const authored = pr({
    roles: ['authored'],
    mergeable: 'CONFLICTING',
    checkState: 'FAILURE',
    failedChecks: ['test'],
  });
  const [first] = candidates(authored);
  assert.equal(first.action, 'conflicts');
  assert.equal(
    candidates(
      { ...authored, baseRefOid: 'new-base' },
      { [first.key]: true },
    )[0].action,
    'conflicts',
  );
  const [fix] = candidates({ ...authored, mergeable: 'MERGEABLE' });
  assert.equal(fix.action, 'ci');
  assert.deepEqual(
    candidates(
      { ...authored, mergeable: 'MERGEABLE', failedChecks: ['other'] },
      { [fix.key]: true },
    ),
    [],
  );
  const fixes = {
    old: {
      auto: true,
      type: 'code',
      kind: 'ci',
      status: 'published',
      url,
      head: 'head',
    },
  };
  assert.deepEqual(
    candidates({ ...authored, mergeable: 'MERGEABLE' }, {}, {}, fixes),
    [],
  );
  assert.equal(
    candidates(
      { ...authored, headRefOid: 'new-head', mergeable: 'MERGEABLE' },
      {},
      {},
      fixes,
    ).length,
    1,
  );
  assert.deepEqual(
    candidates(pr({ checkState: 'FAILURE', roles: ['assigned'] })),
    [],
  );
});

test('publication modes are explicit per action and cannot escalate an in-flight draft', () => {
  for (const action of ['review', 'rereview', 'ci', 'conflicts', 'comments']) {
    const review = action === 'review' || action === 'rereview';
    const initial = {
      action,
      auto: true,
      status: 'pending',
      kind: review ? 'review' : action,
      type: review ? 'review-artifact' : 'code',
      tested: true,
    };
    for (const started of ['draft', 'publish']) {
      const task = { ...initial, requestedMode: started };
      for (const current of ['off', 'draft', 'publish']) {
        const settings = { autoActions: { [action]: current } };
        const expected =
          current === 'off'
            ? null
            : started === 'publish' && current === 'publish'
              ? 'publish'
              : review
                ? 'draft'
                : null;
        assert.equal(
          automaticEffect(task, true, settings),
          expected,
          action + ':' + started + ':' + current,
        );
        assert.equal(automaticEffect(task, false, settings), null);
        assert.equal(
          automaticEffect(
            { ...task, automaticEffect: 'attempted' },
            true,
            settings,
          ),
          null,
        );
        assert.equal(
          automaticEffect({ ...task, auto: false }, true, settings),
          null,
        );
        if (!review)
          assert.equal(
            automaticEffect({ ...task, tested: false }, true, settings),
            null,
          );
      }
    }
  }
});

test('published feedback and unresolved replies produce separate viewer-specific queues', () => {
  const comment = (login, createdAt) => ({ author: { login }, createdAt });
  const thread = (id, author, last, flags) => ({
    id,
    root: { nodes: [comment(author, '2026-01-01')] },
    recent: {
      nodes: [comment(author, '2026-01-01'), comment(last, '2026-01-03')],
    },
    ...flags,
  });
  const p = {
    state: 'OPEN',
    headRefOid: 'head',
    author: { login: 'else' },
    mergeStateStatus: 'CLEAN',
    mergeable: 'MERGEABLE',
    reviews: {
      nodes: [
        {
          state: 'COMMENTED',
          author: { login: 'me' },
          submittedAt: '2026-01-02',
          commit: { oid: 'head' },
        },
      ],
    },
    reviewThreads: {
      nodes: [
        thread('my-thread', 'Me', 'else'),
        thread('resolved', 'me', 'else', { isResolved: true }),
        thread('other-conversation', 'other', 'else'),
      ],
    },
  };
  const reviewer = pullStatus(pr(), p, 'me');
  assert.equal(reviewer.responseFingerprint, 'my-thread:2026-01-03');
  assert.equal(reviewer.pendingResponse, true);
  assert.equal(reviewer.readyToMerge, true);
  assert.equal(reviewer.reviewedCurrentHead, true);
  const authored = pullStatus(pr(), { ...p, author: { login: 'ME' } }, 'me');
  assert.equal(authored.pendingResponse, false);
  assert.equal(authored.unaddressedComments, 2);
});

test('structured comments only create pending reviews unless publish is explicitly authorized', async () => {
  const task = {
    auto: true,
    viewer: 'me',
    url,
    head: 'head',
    type: 'review-artifact',
    status: 'pending',
    body: '',
    comments: [
      {
        path: 'a.js',
        line: 3,
        side: 'RIGHT',
        body: 'Use the verified replacement.\n\n```suggestion\nupdated();\n```',
      },
    ],
  };
  let head = 'head',
    pending = false;
  const writes = [];
  const execute = async (_file, args) => {
    if (args[0] === 'pr')
      return JSON.stringify({
        headRefOid: head,
        state: 'OPEN',
        author: { login: 'other' },
      });
    if (args.at(-1) === 'user') return '{"login":"me"}';
    if (!args.includes('--method'))
      return JSON.stringify([
        pending ? [{ id: 1, state: 'PENDING', user: { login: 'me' } }] : [],
      ]);
    writes.push(JSON.parse(await fs.readFile(args.at(-1), 'utf8')));
    return '{"id":2}';
  };
  await materializeReview(task, 'draft', execute);
  assert.equal(writes[0].commit_id, 'head');
  assert.equal(Object.hasOwn(writes[0], 'event'), false);
  assert.deepEqual(writes[0].comments, task.comments);
  await materializeReview(task, 'publish', execute);
  assert.equal(writes[1].event, 'COMMENT');
  head = 'changed';
  await assert.rejects(
    materializeReview(task, 'publish', execute),
    /PR changed/,
  );
  head = 'head';
  pending = true;
  await assert.rejects(
    materializeReview(task, 'publish', execute),
    /pending GitHub review/,
  );
  pending = false;
  await assert.rejects(
    materializeReview(task, 'publish', execute, () => false),
    /settings changed/,
  );
  assert.equal(writes.length, 2);
});

