test('prepared checkout paths can be isolated from a user repository', async () => {
  const directory = await fs.mkdtemp(
    path.join(os.tmpdir(), 'opusdesk-automatic-'),
  );
  try {
    const { prepareAutomaticCheckout } =
      await import('../server/auto-checkout.js');
    const calls = [];
    const execute = async (command, args) => {
      calls.push([command, ...args]);
      if (args.includes('rev-parse'))
        return args.at(-1).endsWith('/head') ? 'head' : 'base';
      return '';
    };
    const result = await prepareAutomaticCheckout(
      { directory, pull: pr({ baseRefName: 'main' }), kind: 'review' },
      execute,
    );
    assert.equal(result.cwd, path.join(directory, 'checkout'));
    assert.ok(
      calls.some((call) =>
        call.includes('+refs/pull/1/head:refs/opusdesk/head'),
      ),
    );
    assert.ok(
      calls.some((call) =>
        call.includes('+refs/heads/main:refs/opusdesk/base'),
      ),
    );
    await assert.rejects(
      prepareAutomaticCheckout(
        {
          directory,
          pull: pr({ baseRefName: 'main', headRefOid: 'different' }),
          kind: 'review',
        },
        execute,
      ),
      /changed/,
    );
  } finally {
    await fs.rm(directory, { recursive: true, force: true });
  }
});

